/**
 * Writes www/js/config.js from CAPACITOR_SERVER_URL (same origin as capacitor.config.ts).
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const origin = (process.env.CAPACITOR_SERVER_URL ?? 'https://www.conninter.com').replace(/\/+$/, '');
const appHome = `${origin}/app/`;
const outDir = join(root, 'www', 'js');
mkdirSync(outDir, { recursive: true });
const out = join(outDir, 'config.js');

const body = `/* Generated by scripts/write-www-config.mjs — do not edit by hand */
window.__CONNINTER__ = {
  origin: ${JSON.stringify(origin)},
  appHome: ${JSON.stringify(appHome)},
  onboardingVersion: '3',
};
`;

writeFileSync(out, body, 'utf8');
console.log('Wrote', out, '→', appHome);
